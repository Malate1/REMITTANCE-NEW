                        //             </div>
                        //         </td>
                        //     </tr>
                        // `);
                        // },
                        error: function (xhr, status, error) {
                            console.error("AJAX Error:", error);
                            $('#cashier_sm_ledger tbody').html(`
                                <tr>
                                    <td colspan="20" class="text-center text-danger">
                                        Failed to load data
                                    </td>
                                </tr>
                            `);
                        }
                    },

                    columns: [
                        { data: 'checkbox' },
