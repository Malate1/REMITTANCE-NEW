            let smTable;
            let previousDate = null; // global variable to track last selected date
            function formatReadableDate(dateString) {
                const options = { year: "numeric", month: "long", day: "numeric" };
                const date = new Date(dateString);
                return date.toLocaleDateString("en-US", options);
            }

            function updateHeaderDate(dateString) {
                const formattedDate = formatReadableDate(dateString);
                $("#display-date").text(formattedDate);
            }

            function loadTable(date) {
                // if ($.fn.DataTable.isDataTable('#cashier_sm_ledger')) {
                //     $('#cashier_sm_ledger').DataTable().clear().destroy();
                // }

                const tableId = '#cashier_sm_ledger';

                // If table exists, store current page
                let currentPage = 0;
                let isSameDate = (previousDate === date);

                if ($.fn.DataTable.isDataTable(tableId)) {
                    const existingTable = $(tableId).DataTable();
                    currentPage = existingTable.page();
                    existingTable.clear().destroy();
                }

                // Update the previousDate for future comparison
                previousDate = date;

                smTable = $('#cashier_sm_ledger').DataTable({
                    processing: true,
                    serverSide: true,
                    scrollX: true,
                    // stateSave: true,
                    fixedColumns: {
                        leftColumns: 4,
                        rightColumns: 4
                    },
                    ajax: {
                        url: "<?= site_url('get_cashier_sm_data_ajax') ?>",
                        type: "POST",
                        data: function (d) {
                            d.date = date; // send date to server
                        },

                        // beforeSend: function () {
